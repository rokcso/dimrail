#!/usr/bin/env node
/**
 * Dimrail 配置生成脚本
 *
 * 读取 configs/clash.yaml（含你的手写分流规则与 rule-providers），
 * 仅把 proxy-providers 段和代理组的 use 列表替换为运行时标记，
 * 生成 workers/src/config.generated.js，由 Worker 在请求时注入真实订阅源。
 *
 * 用法: npm run generate（deploy / dev 脚本会自动先执行本步骤）
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceFile = resolve(root, 'configs/clash.yaml');
const outDir = resolve(root, 'workers/src');
const outFile = resolve(outDir, 'config.generated.js');

const config = readFileSync(sourceFile, 'utf8');

// 1) proxy-providers 段 → 运行时标记（保留紧随其后的顶层注释/键）
const step1 = config.replace(
  /^proxy-providers:[\s\S]*?(?=^#|^[A-Za-z0-9_-]+:)/m,
  'proxy-providers:\n  # __PROXY_PROVIDERS__\n'
);

// 2) 代理组 use 列表 → 运行时标记（模板统一使用 flow 风格 use: [ProxyProviderA]）
const step2 = step1.replaceAll('use: [ProxyProviderA]', 'use: [__PROVIDER_NAMES__]');

if (!step2.includes('__PROXY_PROVIDERS__')) {
  console.error('❌ 未能在 configs/clash.yaml 中找到 proxy-providers 段');
  process.exit(1);
}
if (!step2.includes('__PROVIDER_NAMES__')) {
  console.error('❌ 未能在 configs/clash.yaml 中找到 use: [ProxyProviderA]，请检查代理组的 use 写法');
  process.exit(1);
}

// 3) 转义为 JS 模板字符串并写入生成模块
const escaped = step2.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
const banner =
  '// Auto-generated by scripts/generate.mjs — do not edit.\n' +
  '// Source: configs/clash.yaml（请直接修改 configs/clash.yaml 后重新生成）\n\n' +
  `export const CONFIG_TEMPLATE = \`${escaped}\`;\n`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, banner, 'utf8');
console.log(`✅ 已生成 ${outFile}（${Buffer.byteLength(step2, 'utf8')} bytes）`);
